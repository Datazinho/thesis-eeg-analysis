# ============================================================
# ΔΙΠΛΩΜΑΤΙΚΗ ΕΡΓΑΣΙΑ - Ανάλυση EEG με Θεωρία Γράφων
# ============================================================
# Αρχείο  : step1_load.py
# Σκοπός  : Φόρτωση ενός EEG αρχείου (1 subject, 1 run)
#           και επαλήθευση ότι τα δεδομένα είναι σωστά
# Βήμα    : 1 από 6
# ============================================================
# ΤΙ ΚΑΝΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ:
# Διαβάζει ένα αρχείο .edf από το dataset (Subject 001, Run 03)
# και εκτυπώνει τα βασικά χαρακτηριστικά του:
#   - Πόσα κανάλια (ηλεκτρόδια) έχει → πρέπει να είναι 64
#   - Ποια είναι η συχνότητα δειγματοληψίας → πρέπει να είναι 160 Hz
#   - Πόσο διαρκεί η καταγραφή → περίπου 120 δευτερόλεπτα
#   - Ποια annotations (T0, T1, T2) υπάρχουν και πόσες φορές
# ============================================================

# --- ΒΙΒΛΙΟΘΗΚΕΣ ---
# Εισάγουμε τις βιβλιοθήκες που χρειαζόμαστε

import mne        # Η κύρια βιβλιοθήκη για EEG - διαβάζει αρχεία .edf
import os         # Για να δουλεύουμε με διαδρομές αρχείων (paths)

# ============================================================
# ΒΗΜΑ 1: Ορισμός διαδρομής (path) του dataset
# ============================================================
# Εδώ λέμε στον Python πού βρίσκεται το dataset στον υπολογιστή
# r"..." σημαίνει "raw string" - αγνοεί τα \ ώστε να μη μπερδευτεί
# με χαρακτήρες escape (π.χ. \n = νέα γραμμή)

DATA_PATH = r"C:\Users\ctsio\OneDrive\Desktop\BNP-My Thesis\me matzako\dataset"

# ============================================================
# ΒΗΜΑ 2: Επιλογή του αρχείου που θέλουμε να φορτώσουμε
# ============================================================
# Ξεκινάμε με Subject 001, Run 03
# Run 03 = Motor Imagery αριστερού/δεξιού χεριού
# Αυτό είναι το πρώτο run κινητικής φαντασίωσης στο dataset

SUBJECT = "S001"   # Ο πρώτος συμμετέχων
RUN     = "R03"    # Run 03 = Motor Imagery χεριού

# os.path.join: φτιάχνει τη διαδρομή σωστά ανεξάρτητα από λειτουργικό σύστημα
# Αποτέλεσμα: C:\...\dataset\S001\S001R03.edf
file_path = os.path.join(DATA_PATH, SUBJECT, f"{SUBJECT}{RUN}.edf")

# ============================================================
# ΒΗΜΑ 3: Έλεγχος αν το αρχείο υπάρχει
# ============================================================
# Πριν προσπαθήσουμε να διαβάσουμε το αρχείο,
# ελέγχουμε αν υπάρχει στη διαδρομή που δώσαμε

print("=" * 60)
print("STEP 1 - Φόρτωση EEG Δεδομένων")
print("=" * 60)
print(f"\nΑρχείο: {file_path}")

if not os.path.exists(file_path):
    # Αν το αρχείο δεν βρεθεί, σταματάμε και εκτυπώνουμε σφάλμα
    print("\n❌ ΣΦΑΛΜΑ: Το αρχείο δεν βρέθηκε!")
    print("   Έλεγξε ότι:")
    print("   1. Το dataset είναι κατεβασμένο")
    print("   2. Η διαδρομή DATA_PATH είναι σωστή")
    exit()  # Σταματάμε εδώ
else:
    print("✅ Το αρχείο βρέθηκε!")

# ============================================================
# ΒΗΜΑ 4: Φόρτωση του αρχείου EDF με MNE-Python
# ============================================================
# mne.io.read_raw_edf() : διαβάζει αρχεία EDF/EDF+ format
# preload=True          : φορτώνει ΟΛΑ τα δεδομένα στη μνήμη αμέσως
#                         (χρειάζεται περισσότερη RAM αλλά είναι πιο γρήγορο)
# verbose=False         : δεν εκτυπώνει πολλά μηνύματα από το MNE

print("\nΦόρτωση αρχείου...")
raw = mne.io.read_raw_edf(file_path, preload=True, verbose=False)
print("✅ Φόρτωση επιτυχής!")

# ============================================================
# ΒΗΜΑ 5: Εκτύπωση βασικών χαρακτηριστικών
# ============================================================
# Τώρα ελέγχουμε αν τα δεδομένα έχουν τα σωστά χαρακτηριστικά

print("\n--- ΧΑΡΑΚΤΗΡΙΣΤΙΚΑ ΑΡΧΕΙΟΥ ---")

# raw.ch_names : λίστα με τα ονόματα όλων των καναλιών (ηλεκτροδίων)
# len()        : μετράει πόσα κανάλια υπάρχουν
# Αναμένουμε: 64 κανάλια EEG
n_channels = len(raw.ch_names)
print(f"Αριθμός καναλιών : {n_channels}  (αναμένεται: 64)")

# raw.info['sfreq'] : η συχνότητα δειγματοληψίας σε Hz
# Αναμένουμε: 160 Hz
sfreq = raw.info['sfreq']
print(f"Συχνότητα         : {sfreq} Hz  (αναμένεται: 160 Hz)")

# raw.times[-1] : ο τελευταίος χρόνος = διάρκεια σε δευτερόλεπτα
# Αναμένουμε: περίπου 120 δευτερόλεπτα (2 λεπτά)
duration = raw.times[-1]
print(f"Διάρκεια          : {duration:.1f} δευτερόλεπτα  (αναμένεται: ~120)")

# ============================================================
# ΒΗΜΑ 6: Έλεγχος Annotations (T0, T1, T2)
# ============================================================
# Τα annotations είναι οι "σημάνσεις" που λένε πότε ξεκίνησε
# κάθε πειραματική συνθήκη:
#   T0 = ηρεμία (rest)
#   T1 = κίνηση/φαντασίωση αριστερού χεριού
#   T2 = κίνηση/φαντασίωση δεξιού χεριού

print("\n--- ANNOTATIONS (Σημάνσεις) ---")

# raw.annotations : αντικείμενο που περιέχει όλες τις σημάνσεις
# .description    : το όνομα κάθε annotation (T0, T1, T2)

# Μετράμε πόσες φορές εμφανίζεται κάθε annotation
annotations = raw.annotations
count_T0 = sum(1 for desc in annotations.description if 'T0' in desc)
count_T1 = sum(1 for desc in annotations.description if 'T1' in desc)
count_T2 = sum(1 for desc in annotations.description if 'T2' in desc)

print(f"T0 (ηρεμία)           : {count_T0} φορές  (αναμένεται: ~15)")
print(f"T1 (αριστερό χέρι)    : {count_T1} φορές  (αναμένεται: 7 ή 8)")
print(f"T2 (δεξί χέρι)        : {count_T2} φορές  (αναμένεται: 7 ή 8)")

# Εκτυπώνουμε και τη λίστα όλων των annotations για οπτικό έλεγχο
print(f"\nΌλα τα annotations: {list(annotations.description)}")

# ============================================================
# ΒΗΜΑ 7: Τελικός έλεγχος — Είναι όλα σωστά;
# ============================================================

print("\n--- ΤΕΛΙΚΟΣ ΕΛΕΓΧΟΣ ---")

# Ελέγχουμε αν όλα τα χαρακτηριστικά είναι στα αναμενόμενα όρια
ok_channels = (n_channels == 64)
ok_sfreq    = (sfreq == 160.0)
ok_T0       = (count_T0 > 0)
ok_T1       = (count_T1 > 0)
ok_T2       = (count_T2 > 0)

if ok_channels and ok_sfreq and ok_T0 and ok_T1 and ok_T2:
    print("✅ ΟΛΑ ΣΩΣΤΑ! Το αρχείο είναι έγκυρο και έτοιμο για ανάλυση.")
else:
    print("⚠️  ΠΡΟΒΛΗΜΑ:")
    if not ok_channels:
        print(f"   - Λάθος αριθμός καναλιών: {n_channels} (αναμένεται 64)")
    if not ok_sfreq:
        print(f"   - Λάθος συχνότητα: {sfreq} (αναμένεται 160)")
    if not ok_T0:
        print("   - Δεν βρέθηκαν annotations T0")
    if not ok_T1:
        print("   - Δεν βρέθηκαν annotations T1")
    if not ok_T2:
        print("   - Δεν βρέθηκαν annotations T2")

print("\n" + "=" * 60)
print("Επόμενο βήμα: step2_filter.py")
print("=" * 60)
